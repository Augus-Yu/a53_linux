static HI_VOID GammaUsrRegsInit(ISP_GAMMA_USR_CFG_S *pstUsrRegCfg, const HI_U16 *pau16Gamma)
{
    pstUsrRegCfg->bResh = HI_TRUE;
    pstUsrRegCfg->bGammaLutUpdateEn = HI_TRUE;
    pstUsrRegCfg->u32UpdateIndex = 1;
    memcpy(pstUsrRegCfg->au16GammaLUT, pau16Gamma, GAMMA_NODE_NUMBER * sizeof(HI_U16));
}

static HI_S32 GammaCheckCmosParam(VI_PIPE ViPipe, const hi_isp_cmos_gamma *cmos_gamma)
{
    HI_U16 i;

    for (i = 0; i < GAMMA_NODE_NUMBER; i++) {
        if (cmos_gamma->gamma_lut[i] > 0xFFF) {
            ISP_ERR_TRACE("Invalid au16Gamma[%d]!\n", i);
            return HI_ERR_ISP_ILLEGAL_PARAM;
        }
    }

    return HI_SUCCESS;
}

static HI_S32 GammaRegsInitialize(VI_PIPE ViPipe, isp_reg_cfg *pstRegCfg)
{
    HI_U8 u8WDRMode;
    HI_U16 i;
    HI_S32 s32Ret;
    const HI_U16 *pau16GAMMA = HI_NULL;
    ISP_GAMMA_S *pstGammaCtx = HI_NULL;
    isp_usr_ctx   *pstIspCtx   = HI_NULL;
    hi_isp_cmos_default *sns_dft = HI_NULL;

    isp_sensor_get_default(ViPipe,&sns_dft);
    ISP_GET_CTX(ViPipe, pstIspCtx);
    GAMMA_GET_CTX(ViPipe, pstGammaCtx);

    pstGammaCtx->bEnable = HI_TRUE;
    pstGammaCtx->bLutUpdate = HI_TRUE;

    u8WDRMode = pstIspCtx->sns_wdr_mode;

    /* Read from CMOS */
    if (sns_dft->key.bit1_gamma) {
        ISP_CHECK_POINTER(sns_dft->gamma);

        s32Ret = GammaCheckCmosParam(ViPipe, sns_dft->gamma);
        if (s32Ret != HI_SUCCESS) {
            return s32Ret;
        }

        pau16GAMMA = sns_dft->gamma->gamma_lut;
        hi_ext_system_gamma_curve_type_write(ViPipe, ISP_GAMMA_CURVE_USER_DEFINE);
    } else { /* Read from firmware */
        if (IS_LINEAR_MODE(u8WDRMode)) {
            pau16GAMMA = g_au16LinModeGamma;
        } else {
            pau16GAMMA = g_au16WDRModeGamma;
        }
    }

    for (i = 0; i < GAMMA_NODE_NUMBER; i++) {
        hi_ext_system_gamma_lut_write(ViPipe, i, pau16GAMMA[i]);
    }

    for (i = 0; i < pstRegCfg->cfg_num; i++) {
        GammaUsrRegsInit(&pstRegCfg->alg_reg_cfg[i].stGammaCfg.stUsrRegCfg, pau16GAMMA);
        pstRegCfg->alg_reg_cfg[i].stGammaCfg.bGammaEn = HI_TRUE;
    }

    pstRegCfg->cfg_key.bit1GammaCfg = 1;

    return HI_SUCCESS;
}

static HI_VOID GammaExtRegsInitialize(VI_PIPE ViPipe)
{
    // Only extern reg is gamma curve type
    hi_ext_system_gamma_en_write(ViPipe, HI_TRUE);
    hi_ext_system_gamma_lut_update_write(ViPipe, HI_FALSE);
    hi_ext_system_gamma_curve_type_write(ViPipe, HI_EXT_SYSTEM_GAMMA_CURVE_TYPE_DEFAULT);
}

static HI_S32 GammaReadExtRegs(VI_PIPE ViPipe)
{
    ISP_GAMMA_S *pstGammaCtx = HI_NULL;

    GAMMA_GET_CTX(ViPipe, pstGammaCtx);

    pstGammaCtx->bLutUpdate = hi_ext_system_gamma_lut_update_read(ViPipe);
    hi_ext_system_gamma_lut_update_write(ViPipe, HI_FALSE);

    return HI_SUCCESS;
}

HI_S32 ISP_GammaInit(VI_PIPE ViPipe, HI_VOID *pRegCfg)
{
    HI_S32 s32Ret;
    isp_reg_cfg *pstRegCfg = (isp_reg_cfg *)pRegCfg;

    GammaExtRegsInitialize(ViPipe);
    s32Ret = GammaRegsInitialize(ViPipe, pstRegCfg);
    if (s32Ret != HI_SUCCESS) {
        return s32Ret;
    }

    return HI_SUCCESS;
}

static HI_VOID ISP_GammaWdrModeSet(VI_PIPE ViPipe, HI_VOID *pRegCfg)
{
    HI_U8 i;
    HI_U32 au32UpdateIdx[ISP_STRIPING_MAX_NUM] = { 0 };
    isp_reg_cfg *pstRegCfg = (isp_reg_cfg *)pRegCfg;

    for (i = 0; i < pstRegCfg->cfg_num; i++) {
        au32UpdateIdx[i] = pstRegCfg->alg_reg_cfg[i].stGammaCfg.stUsrRegCfg.u32UpdateIndex;
    }

    ISP_GammaInit(ViPipe, pRegCfg);

    for (i = 0; i < pstRegCfg->cfg_num; i++) {
        pstRegCfg->alg_reg_cfg[i].stGammaCfg.stUsrRegCfg.u32UpdateIndex = au32UpdateIdx[i] + 1;
    }
}

static HI_BOOL __inline CheckGammaOpen(ISP_GAMMA_S *pstGamma)
{
    return (pstGamma->bEnable == HI_TRUE);
}

HI_S32 ISP_GammaRun(VI_PIPE ViPipe, const HI_VOID *pStatInfo,
                    HI_VOID *pRegCfg, HI_S32 s32Rsv)
{
    HI_U16 i, j;
    isp_reg_cfg *pstReg = (isp_reg_cfg *)pRegCfg;

    ISP_GAMMA_S *pstGammaCtx = HI_NULL;
    ISP_GAMMA_USR_CFG_S *pstUsrRegCfg = HI_NULL;
    GAMMA_GET_CTX(ViPipe, pstGammaCtx);

    pstGammaCtx->bEnable = hi_ext_system_gamma_en_read(ViPipe);

    for (i = 0; i < pstReg->cfg_num; i++) {
        pstReg->alg_reg_cfg[i].stGammaCfg.bGammaEn = pstGammaCtx->bEnable;
    }

    pstReg->cfg_key.bit1GammaCfg = 1;

    /* check hardware setting */
    if (!CheckGammaOpen(pstGammaCtx)) {
        return HI_SUCCESS;
    }

    GammaReadExtRegs(ViPipe);

    if (pstGammaCtx->bLutUpdate) {
        for (i = 0; i < pstReg->cfg_num; i++) {
            pstUsrRegCfg = &pstReg->alg_reg_cfg[i].stGammaCfg.stUsrRegCfg;
            for (j = 0; j < GAMMA_NODE_NUMBER; j++) {
                pstUsrRegCfg->au16GammaLUT[j] = hi_ext_system_gamma_lut_read(ViPipe, j);
            }
            pstUsrRegCfg->bGammaLutUpdateEn = HI_TRUE;
            pstUsrRegCfg->u32UpdateIndex += 1;
        }
    }

    return HI_SUCCESS;
}

HI_S32 ISP_GammaCtrl(VI_PIPE ViPipe, HI_U32 u32Cmd, HI_VOID *pValue)
{
    isp_reg_cfg_attr *pRegCfg = HI_NULL;

    switch (u32Cmd) {
        case ISP_WDR_MODE_SET:
            ISP_REGCFG_GET_CTX(ViPipe, pRegCfg);
            ISP_CHECK_POINTER(pRegCfg);
            ISP_GammaWdrModeSet(ViPipe, (HI_VOID *)&pRegCfg->reg_cfg);
            break;
        default:
            break;
    }

    return HI_SUCCESS;
}

HI_S32 ISP_GammaExit(VI_PIPE ViPipe)
{
    return HI_SUCCESS;
}

HI_S32 isp_alg_register_gamma(VI_PIPE ViPipe)
{
    isp_usr_ctx *pstIspCtx = HI_NULL;
    isp_alg_node *pstAlgs = HI_NULL;

    ISP_GET_CTX(ViPipe, pstIspCtx);

    pstAlgs = ISP_SearchAlg(pstIspCtx->algs);
    ISP_CHECK_POINTER(pstAlgs);

    pstAlgs->alg_type = ISP_ALG_GAMMA;
    pstAlgs->alg_func.pfn_alg_init = ISP_GammaInit;
    pstAlgs->alg_func.pfn_alg_run = ISP_GammaRun;
    pstAlgs->alg_func.pfn_alg_ctrl = ISP_GammaCtrl;
    pstAlgs->alg_func.pfn_alg_exit = ISP_GammaExit;
    pstAlgs->used = HI_TRUE;

    return HI_SUCCESS;
}

